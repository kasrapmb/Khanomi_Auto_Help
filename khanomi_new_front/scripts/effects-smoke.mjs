import {chromium} from '@playwright/test';
import assert from 'node:assert/strict';
const browser=await chromium.launch({executablePath:process.env.CHROMIUM_PATH||'/usr/bin/chromium',args:['--no-sandbox']});
try {
 const page=await browser.newPage({viewport:{width:1672,height:941},reducedMotion:'no-preference'});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto(process.env.APP_URL||'http://127.0.0.1:5173');
 await page.evaluate(()=>document.fonts.ready);
 await page.locator('.metric').first().hover({position:{x:45,y:55}});
 await page.waitForFunction(()=>document.querySelector('.metric').classList.contains('pointer-lit'));
 assert.notEqual(await page.locator('.metric').first().evaluate(e=>e.style.getPropertyValue('--pointer-x')),'');
 await page.evaluate(()=>Promise.all(document.getAnimations().filter(a=>a.effect.getTiming().iterations!==Infinity).map(a=>a.finished.catch(()=>{}))));
 await page.screenshot({path:'artifacts/effects-hover.png',fullPage:true});
 await page.locator('.periods button').first().click();
 assert.ok(await page.locator('.click-ripple').count()>0);
 const toggle=page.locator('.motion-toggle');
 await toggle.click();
 assert.equal(await page.locator('body').getAttribute('data-motion'),'off');
 assert.equal(await page.locator('.coin').evaluate(e=>getComputedStyle(e).animationName),'none');
 await page.reload();
 assert.equal(await page.locator('body').getAttribute('data-motion'),'off');
 await page.locator('.motion-toggle').click();
 assert.equal(await page.locator('body').getAttribute('data-motion'),'on');
 await page.emulateMedia({reducedMotion:'reduce'});
 await page.waitForFunction(()=>document.body.dataset.motion==='off');
 assert.equal(await page.locator('.aurora').first().evaluate(e=>getComputedStyle(e).animationName),'none');
 assert.equal(await page.locator('.pointer-lit').count(),0);
 await page.locator('[data-dialog="تحلیل مالی"]').click();
 assert.equal(await page.locator('dialog').evaluate(e=>e.open),true);
 await page.keyboard.press('Escape');
 await page.emulateMedia({reducedMotion:'no-preference'});
 await page.setViewportSize({width:390,height:844});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
 assert.deepEqual(errors,[]);
 const touch=await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
 const mobile=await touch.newPage();await mobile.goto(process.env.APP_URL||'http://127.0.0.1:5173');
 await mobile.locator('[data-dialog="تحلیل مالی"]').tap();
 assert.equal(await mobile.locator('dialog').evaluate(e=>e.open),true);
 assert.equal(await mobile.locator('.pointer-lit').count(),0);
 await touch.close();
 console.log('PASS: pointer glow, click ripple, persisted toggle, OS reduced motion, mobile touch and no browser errors');
} finally {await browser.close();}
